-- NABABI attendance event stream used by the Super Admin weekly report.
-- Existing staff and legacy attendance rows are not modified.
create table if not exists public.staff_attendance_events (
  id bigint generated by default as identity primary key,
  staff_id uuid not null,
  event_type text not null check (event_type in ('check_in', 'check_out')),
  occurred_at timestamptz not null default now(),
  source text not null default 'qr',
  created_at timestamptz not null default now()
);

create index if not exists staff_attendance_events_staff_time_idx
  on public.staff_attendance_events (staff_id, occurred_at desc, id desc);

alter table public.staff_attendance_events enable row level security;

drop policy if exists nababi_admin_read_attendance_events
  on public.staff_attendance_events;
create policy nababi_admin_read_attendance_events
  on public.staff_attendance_events
  for select to authenticated
  using (exists (
    select 1 from public.admin_users au where au.user_id = auth.uid()
  ));

grant select on public.staff_attendance_events to authenticated;

-- Correct the legacy summary column to match Admin V2's attendance_date field.
create or replace function public.nababi_auto_midnight_checkout()
returns integer
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_now timestamptz;
  v_today date;
  v_closed integer := 0;
  v_open record;
  v_midnight timestamptz;
begin
  perform pg_catalog.pg_advisory_xact_lock(20261109, 1);
  v_now := pg_catalog.clock_timestamp();
  v_today := (v_now at time zone 'Europe/Rome')::date;

  for v_open in
    select latest.staff_id,
           (latest.occurred_at at time zone 'Europe/Rome')::date as work_day
    from (
      select distinct on (e.staff_id)
             e.staff_id, e.event_type, e.occurred_at
      from public.staff_attendance_events as e
      order by e.staff_id, e.occurred_at desc, e.id desc
    ) as latest
    where latest.event_type = 'check_in'
      and (latest.occurred_at at time zone 'Europe/Rome')::date < v_today
  loop
    v_midnight := pg_catalog.make_timestamptz(
      extract(year from v_open.work_day + 1)::integer,
      extract(month from v_open.work_day + 1)::integer,
      extract(day from v_open.work_day + 1)::integer,
      0, 0, 0,
      'Europe/Rome'
    );

    insert into public.staff_attendance_events
      (staff_id, event_type, occurred_at, source)
    values
      (v_open.staff_id, 'check_out', v_midnight, 'auto_midnight');

    update public.staff_attendance
       set check_out = time '00:00',
           status = coalesce(status, 'present')
     where staff_id = v_open.staff_id
       and attendance_date = v_open.work_day;

    v_closed := v_closed + 1;
  end loop;

  return v_closed;
end;
$function$;

-- Schedule only when pg_cron is installed; never make the migration fail
-- solely because the optional extension is unavailable in this project.
do $schedule$
begin
  if to_regclass('cron.job') is not null then
    if not exists (
      select 1 from cron.job
      where jobname = 'nababi-midnight-attendance-checkout'
    ) then
      perform cron.schedule(
        'nababi-midnight-attendance-checkout',
        '* * * * *',
        'select public.nababi_auto_midnight_checkout();'
      );
    end if;
  else
    raise notice 'pg_cron is not installed; enable it to schedule automatic midnight checkout.';
  end if;
end;
$schedule$;
