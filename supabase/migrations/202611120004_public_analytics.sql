-- Minimal privacy-conscious public page-view counter for the Admin dashboard.
-- Stores only the path and timestamp; no IP address, user agent, or personal data.

create table if not exists public.website_analytics (
  id bigint generated by default as identity primary key,
  page_path text not null default '/',
  visited_at timestamptz not null default now()
);

alter table public.website_analytics
  add column if not exists page_path text not null default '/',
  add column if not exists visited_at timestamptz not null default now();

alter table public.website_analytics enable row level security;

drop policy if exists "Public can record page views" on public.website_analytics;
create policy "Public can record page views"
  on public.website_analytics
  for insert
  to anon, authenticated
  with check (
    char_length(page_path) between 1 and 512
    and left(page_path, 1) = '/'
  );

drop policy if exists "Admins can read website analytics" on public.website_analytics;
create policy "Admins can read website analytics"
  on public.website_analytics
  for select
  to authenticated
  using (
    exists (select 1 from public.admin_users au where au.user_id = auth.uid())
  );

grant insert on public.website_analytics to anon, authenticated;
grant select on public.website_analytics to authenticated;
