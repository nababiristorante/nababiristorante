-- Nababi Ristorante: QR menu image pages (separate from menu_items)
create table if not exists public.qr_menu_images (
  id bigint generated by default as identity primary key,
  image_url text not null,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.qr_menu_images enable row level security;

-- Guests can read only pages intentionally published in the QR menu.
drop policy if exists "Public can view active QR menu images" on public.qr_menu_images;
create policy "Public can view active QR menu images"
on public.qr_menu_images for select
to anon, authenticated
using (is_active = true);

-- Only users explicitly registered as admins in admin_users can manage QR pages.
drop policy if exists "Admins manage QR menu images" on public.qr_menu_images;
create policy "Admins manage QR menu images"
on public.qr_menu_images for all
to authenticated
using (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
)
with check (
  exists (select 1 from public.admin_users au where au.user_id = auth.uid())
);

grant select on public.qr_menu_images to anon, authenticated;
grant insert, update, delete on public.qr_menu_images to authenticated;
grant usage, select on sequence public.qr_menu_images_id_seq to authenticated;
